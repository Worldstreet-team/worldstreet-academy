import type * as React from "react"
import { Icon as CxIcon, type IconName, type IconTone } from "@/ds/components/icon"

/**
 * The Academy's one icon entry point (design system, 2026-10-06). Every glyph
 * is the system's duotone set (ds/components/icon, vendored — add new ones to
 * worldstreet/design-system and run `pnpm ds:sync`). The named exports keep
 * the names call sites already used, so a migration was an import change;
 * new code can also use <Icon icon="name"> directly.
 *
 * Tone: the WorldStreet gold gradient by default, including on neutral
 * chrome. When the className sets a colour that carries MEANING (success,
 * danger, warning, ink on gold, white on a photo) — or a `color` is passed —
 * the icon follows currentColor instead. Duotone either way.
 * (GENERATED by the migration codemod; add new names by hand.)
 */
export type IconProps = Omit<React.SVGAttributes<SVGSVGElement>, "name"> & {
  size?: number | string
  /** Accepted for call-site compatibility; the glyphs use a fixed stroke. */
  strokeWidth?: number | string
  absoluteStrokeWidth?: boolean
  tone?: IconTone
}
export type IconComponent = (props: IconProps) => React.ReactElement
export type AppIcon = IconName

const MEANING =
  /(?:^|\s)(?:[a-z-]+:)*text-(?:ws-(?:danger|success|warning|brand-on|rating|forex|crypto|academy)|destructive|primary-foreground|background|white|black|current|red|green|emerald|amber|orange|yellow|rose|sky|blue|violet|\[)/

function toneFor(className?: string, color?: string, tone?: IconTone): IconTone {
  if (tone) return tone
  if (color && color !== "currentColor") return "current"
  return className && MEANING.test(className) ? "current" : "gradient"
}

export function Icon({ icon, ...props }: IconProps & { icon: IconName; label?: string }) {
  return <Glyph icon={glyph(icon)} {...props} />
}

const cache = new Map<string, IconComponent>()
function glyph(name: IconName, displayName?: string): IconComponent {
  const hit = cache.get(name)
  if (hit && !displayName) return hit
  function G({ size, strokeWidth: _sw, absoluteStrokeWidth: _asw, className, color, tone, style, ...rest }: IconProps) {
    void _sw
    void _asw
    const px = typeof size === "number" ? size : size ? Number.parseFloat(size) : undefined
    return (
      <CxIcon
        name={name}
        size={px}
        tone={toneFor(className, color, tone)}
        className={className}
        style={color && color !== "currentColor" ? { color, ...style } : style}
        {...rest}
      />
    )
  }
  G.displayName = displayName ?? name
  if (!hit) cache.set(name, G)
  return G
}

/** For call sites that pick an icon at runtime: <Glyph icon={X} className="…" />. */
export function Glyph({ icon: C, ...props }: IconProps & { icon: IconComponent }) {
  return <C {...props} />
}

